/// One row of `ui-spec/icons.yaml`: an icon key to a Tabler icon name
/// and an optional theme tint token.
#[derive(Debug, Clone, PartialEq, Eq)]
struct IconRow {
    key: String,
    icon: String,
    tint: Option<String>,
}

/// The parsed icon map, sorted by key for deterministic output.
#[derive(Debug, Clone, PartialEq, Eq)]
struct IconCatalog {
    /// The workspace-relative directory that holds the SVGs.
    set_path: String,
    /// Every map row, sorted by key.
    icons: Vec<IconRow>,
}

/// Parses `ui-spec/icons.yaml`. Every error names the offending key;
/// malformed input is never a panic.
fn parse_icon_catalog(text: &str) -> Result<IconCatalog> {
    let root: serde_json::Value =
        serde_saphyr::from_str(text).map_err(|e| format!("{ICONS_INPUT}: {e}"))?;
    let object = root
        .as_object()
        .ok_or_else(|| format!("{ICONS_INPUT}: the document is not a mapping"))?;
    let set = object
        .get("set")
        .and_then(serde_json::Value::as_object)
        .ok_or_else(|| format!("{ICONS_INPUT}: missing `set` mapping"))?;
    let set_path = set
        .get("path")
        .and_then(serde_json::Value::as_str)
        .ok_or_else(|| format!("{ICONS_INPUT}: missing or non-string `set.path`"))?
        .to_owned();
    check_relative_path(&set_path, "set.path")?;
    let icons = object
        .get("icons")
        .and_then(serde_json::Value::as_object)
        .ok_or_else(|| format!("{ICONS_INPUT}: missing `icons` mapping"))?;
    let mut rows = Vec::with_capacity(icons.len());
    for (key, value) in icons {
        let row = value
            .as_object()
            .ok_or_else(|| format!("{ICONS_INPUT}: icon key `{key}` is not a mapping"))?;
        let icon = row
            .get("icon")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| format!("{ICONS_INPUT}: icon key `{key}` has no string `icon`"))?
            .to_owned();
        check_icon_name(&icon, key)?;
        let tint = match row.get("tint") {
            None | Some(serde_json::Value::Null) => None,
            Some(serde_json::Value::String(tint)) => Some(tint.clone()),
            Some(_) => {
                return Err(format!(
                    "{ICONS_INPUT}: icon key `{key}` has a non-string `tint`"
                ));
            }
        };
        rows.push(IconRow {
            key: key.clone(),
            icon,
            tint,
        });
    }
    rows.sort_by(|a, b| a.key.cmp(&b.key));
    Ok(IconCatalog {
        set_path,
        icons: rows,
    })
}

/// Rejects an absolute path or one that can climb out of the workspace;
/// the generator turns this path into `include_bytes!` arguments.
fn check_relative_path(path: &str, what: &str) -> Result<()> {
    let p = Path::new(path);
    if p.is_absolute() {
        return Err(format!("{ICONS_INPUT}: `{what}` is absolute (`{path}`)"));
    }
    for component in p.components() {
        match component {
            std::path::Component::Normal(_) => {}
            std::path::Component::CurDir => {}
            _ => {
                return Err(format!(
                    "{ICONS_INPUT}: `{what}` must not contain `..` (`{path}`)"
                ));
            }
        }
    }
    if path.is_empty() {
        return Err(format!("{ICONS_INPUT}: `{what}` is empty"));
    }
    Ok(())
}

/// Rejects an icon name that is not a plain Tabler file stem.
fn check_icon_name(name: &str, key: &str) -> Result<()> {
    let valid = !name.is_empty()
        && name
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-');
    if valid {
        Ok(())
    } else {
        Err(format!(
            "{ICONS_INPUT}: icon key `{key}` names an invalid icon `{name}`"
        ))
    }
}

/// Renders the icon table and checks that every named SVG exists.
fn generate_icon_outputs(text: &str, root: &Path) -> Result<Vec<Output>> {
    let catalog = parse_icon_catalog(text)?;
    let output = PathBuf::from(ICONS_OUTPUT);
    let output_dir = output
        .parent()
        .ok_or_else(|| format!("{ICONS_OUTPUT}: no parent directory"))?;
    let mut names = BTreeSet::new();
    for row in &catalog.icons {
        names.insert(row.icon.clone());
    }
    for name in &names {
        let file = format!("{}/{name}.svg", catalog.set_path.trim_end_matches('/'));
        let path = root.join(&file);
        if !path.is_file() {
            return Err(format!(
                "{ICONS_INPUT}: icon `{name}` has no file at `{file}`"
            ));
        }
    }
    Ok(vec![(
        output.clone(),
        render_icon_table(&catalog, &names, output_dir),
    )])
}

/// Renders `crates/ui/src/icons/table.rs`: every unique SVG once, then
/// the key-to-icon-and-tint rows (ADR 0062).
fn render_icon_table(catalog: &IconCatalog, names: &BTreeSet<String>, output_dir: &Path) -> String {
    let mut out = String::new();
    out.push_str(ICONS_HEADER);
    out.push_str("\n\n");
    out.push_str(
        "//! The embedded Tabler icon table (ADR 0062).\n\
         //!\n\
         //! Generated from `ui-spec/icons.yaml` by `cargo xtask codegen`.\n\
         //! Do not edit by hand: the gate step `codegen` runs\n\
         //! `cargo xtask codegen --check` and fails on drift.\n\n\
         /// One embedded icon: its Tabler name and SVG bytes.\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct IconDef {\n\
         \x20   /// The Tabler icon name (`scissors`).\n\
         \x20   pub name: &'static str,\n\
         \x20   /// The upstream SVG file, embedded at compile time.\n\
         \x20   pub bytes: &'static [u8],\n\
         }\n\n\
         /// One icon-map row: an icon key to a Tabler icon and an\n\
         /// optional theme tint token.\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct IconEntryDef {\n\
         \x20   /// The icon-map key (usually a command id).\n\
         \x20   pub key: &'static str,\n\
         \x20   /// The Tabler icon name.\n\
         \x20   pub icon: &'static str,\n\
         \x20   /// The theme token that tints the icon, when the map has one.\n\
         \x20   pub tint: Option<&'static str>,\n\
         }\n\n",
    );

    out.push_str("/// Every embedded icon, sorted by Tabler name.\n");
    out.push_str("pub static ICONS: &[IconDef] = &[\n");
    for name in names {
        let file = format!("{name}.svg");
        let relative = relative_include_path(output_dir, Path::new(&catalog.set_path), &file);
        out.push_str("    IconDef {\n");
        out.push_str(&format!("        name: {},\n", literal(name)));
        out.push_str(&format!(
            "        bytes: include_bytes!({}),\n",
            literal(&relative)
        ));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    out.push_str("/// Every icon-map row, sorted by key.\n");
    out.push_str("pub static ENTRIES: &[IconEntryDef] = &[\n");
    for row in &catalog.icons {
        out.push_str("    IconEntryDef {\n");
        out.push_str(&format!("        key: {},\n", literal(&row.key)));
        out.push_str(&format!("        icon: {},\n", literal(&row.icon)));
        match &row.tint {
            Some(tint) => {
                out.push_str(&format!("        tint: Some({}),\n", literal(tint)));
            }
            None => out.push_str("        tint: None,\n"),
        }
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");

    out.push_str(
        "/// The SVG bytes of a Tabler icon, or `None` for an unknown name.\n\
         pub fn icon(name: &str) -> Option<&'static [u8]> {\n\
         \x20   ICONS\n\
         \x20       .binary_search_by_key(&name, |def| def.name)\n\
         \x20       .ok()\n\
         \x20       .and_then(|index| ICONS.get(index))\n\
         \x20       .map(|def| def.bytes)\n\
         }\n\n\
         /// One icon-map row, or `None` for an unknown key.\n\
         pub fn entry(key: &str) -> Option<&'static IconEntryDef> {\n\
         \x20   ENTRIES\n\
         \x20       .binary_search_by_key(&key, |def| def.key)\n\
         \x20       .ok()\n\
         \x20       .and_then(|index| ENTRIES.get(index))\n\
         }\n",
    );
    out
}

/// The `include_bytes!` path from `from_dir` to `file` in `target_dir`,
/// with forward slashes (both paths are workspace-relative).
fn relative_include_path(from_dir: &Path, target_dir: &Path, file: &str) -> String {
    let from: Vec<String> = from_dir
        .iter()
        .map(|part| part.to_string_lossy().into_owned())
        .collect();
    let to: Vec<String> = target_dir
        .iter()
        .map(|part| part.to_string_lossy().into_owned())
        .collect();
    let mut common = 0;
    while common < from.len() && common < to.len() && from[common] == to[common] {
        common += 1;
    }
    let mut parts: Vec<String> =
        std::iter::repeat_n("..".to_owned(), from.len() - common).collect();
    parts.extend(to.iter().skip(common).cloned());
    parts.push(file.to_owned());
    parts.join("/")
}

