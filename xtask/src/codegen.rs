/// One parsed cell of one section.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Cell {
    name: String,
    cell_index: Option<i32>,
    kind: String,
    default_unit: String,
    default_value: Option<String>,
}

/// One parsed section with its cells.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Section {
    name: String,
    section_index: Option<i32>,
    kind: String,
    default_unit: String,
    cells: Vec<Cell>,
}

/// One parsed entry of the global rows table.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Row {
    name: String,
    row_index: i32,
    section: Option<String>,
}

/// The parsed `ui-spec/shapesheet.toml`, sorted for determinism.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Catalog {
    sections: Vec<Section>,
    rows: Vec<Row>,
    cell_indices: Vec<(String, i32)>,
    section_indices: Vec<(String, i32)>,
    row_indices: Vec<(String, i32)>,
}

/// Parses `ui-spec/shapesheet.toml` into a [`Catalog`]. Every error
/// names the offending key; malformed input is never a panic.
fn parse_catalog(text: &str) -> Result<Catalog> {
    let root: toml::Table = toml::from_str(text).map_err(|e| format!("{INPUT}: {e}"))?;
    let root = &root;

    let mut sections = Vec::new();
    for (i, value) in array_field(root, "sections", INPUT)?.iter().enumerate() {
        let ctx = format!("sections[{i}]");
        let t = as_table(value, &ctx)?;
        let mut cells = Vec::new();
        if let Some(cell_values) = t.get("cells") {
            let cell_values = cell_values
                .as_array()
                .ok_or_else(|| format!("{ctx}.cells: not an array"))?;
            for (j, cell_value) in cell_values.iter().enumerate() {
                let cctx = format!("{ctx}.cells[{j}]");
                let ct = as_table(cell_value, &cctx)?;
                let kind = string_field(ct, "type", &cctx)?;
                if !matches!(
                    kind.as_str(),
                    "Number" | "String" | "Bool" | "Color" | "List"
                ) {
                    return Err(format!(
                        "{cctx}: unknown cell type `{kind}` (want Number, String, Bool, Color or List)"
                    ));
                }
                cells.push(Cell {
                    name: string_field(ct, "name", &cctx)?,
                    cell_index: optional_index_field(ct, "cell_index", &cctx)?,
                    kind,
                    default_unit: string_field(ct, "default_unit", &cctx)?,
                    default_value: optional_string_field(ct, "default_value", &cctx)?,
                });
            }
        }
        cells.sort_by(|a, b| a.name.cmp(&b.name));
        let kind = string_field(t, "kind", &ctx)?;
        if !matches!(kind.as_str(), "object" | "collection") {
            return Err(format!(
                "{ctx}: unknown kind `{kind}` (want `object` or `collection`)"
            ));
        }
        sections.push(Section {
            name: string_field(t, "name", &ctx)?,
            section_index: optional_index_field(t, "section_index", &ctx)?,
            kind,
            default_unit: string_field(t, "default_unit", &ctx)?,
            cells,
        });
    }
    sections.sort_by(|a, b| a.name.cmp(&b.name));

    let mut rows = Vec::new();
    for (i, value) in array_field(root, "rows", INPUT)?.iter().enumerate() {
        let ctx = format!("rows[{i}]");
        let t = as_table(value, &ctx)?;
        rows.push(Row {
            name: string_field(t, "name", &ctx)?,
            row_index: index_field(t, "row_index", &ctx)?,
            section: optional_string_field(t, "section", &ctx)?,
        });
    }
    rows.sort_by(|a, b| a.name.cmp(&b.name));

    let enums = root
        .get("enumerations")
        .ok_or(format!("{INPUT}: missing `enumerations` table"))?;
    let enums = as_table(enums, "enumerations")?;
    let catalog = Catalog {
        sections,
        rows,
        cell_indices: index_map_field(enums, "vis_cell_indices", "enumerations")?,
        section_indices: index_map_field(enums, "vis_section_indices", "enumerations")?,
        row_indices: index_map_field(enums, "vis_row_indices", "enumerations")?,
    };
    check_unique("section", catalog.sections.iter().map(|s| s.name.as_str()))?;
    check_unique("row", catalog.rows.iter().map(|r| r.name.as_str()))?;
    for section in &catalog.sections {
        check_unique(
            &format!("cell of section `{}`", section.name),
            section.cells.iter().map(|c| c.name.as_str()),
        )?;
    }
    Ok(catalog)
}

/// Fails when `values` holds a duplicate name.
fn check_unique<'a>(what: &str, values: impl Iterator<Item = &'a str>) -> Result<()> {
    let mut seen: Vec<&str> = Vec::new();
    for value in values {
        if seen.contains(&value) {
            return Err(format!("duplicate {what} name `{value}`"));
        }
        seen.push(value);
    }
    Ok(())
}

/// The value of `key` as a table, or an error naming `ctx`.
fn as_table<'a>(value: &'a toml::Value, ctx: &str) -> Result<&'a toml::Table> {
    value
        .as_table()
        .ok_or_else(|| format!("{ctx}: not a table"))
}

/// The array value of `key`, or an error naming `ctx`.`key`.
fn array_field<'a>(table: &'a toml::Table, key: &str, ctx: &str) -> Result<&'a Vec<toml::Value>> {
    table
        .get(key)
        .and_then(toml::Value::as_array)
        .ok_or_else(|| format!("{ctx}: missing `{key}` array"))
}

/// The string value of `key`, or an error naming `ctx`.`key`.
fn string_field(table: &toml::Table, key: &str, ctx: &str) -> Result<String> {
    table
        .get(key)
        .and_then(toml::Value::as_str)
        .map(str::to_owned)
        .ok_or_else(|| format!("{ctx}: missing or non-string `{key}`"))
}

/// The optional string value of `key`; a present non-string is an
/// error naming `ctx`.`key`.
fn optional_string_field(table: &toml::Table, key: &str, ctx: &str) -> Result<Option<String>> {
    match table.get(key).map(toml::Value::as_str) {
        None => Ok(None),
        Some(Some(s)) => Ok(Some(s.to_owned())),
        Some(None) => Err(format!("{ctx}: `{key}` is not a string")),
    }
}

/// The optional integer value of `key` as `i32`; a present value that
/// is not an integer or does not fit names `ctx`.`key`.
fn optional_index_field(table: &toml::Table, key: &str, ctx: &str) -> Result<Option<i32>> {
    match table.get(key).map(toml::Value::as_integer) {
        None => Ok(None),
        Some(Some(raw)) => i32::try_from(raw)
            .map(Some)
            .map_err(|_| format!("{ctx}: `{key}` value {raw} does not fit in i32")),
        Some(None) => Err(format!("{ctx}: `{key}` is not an integer")),
    }
}

/// The integer value of `key` as `i32`, or an error naming `ctx`.`key`.
fn index_field(table: &toml::Table, key: &str, ctx: &str) -> Result<i32> {
    let raw = table
        .get(key)
        .and_then(toml::Value::as_integer)
        .ok_or_else(|| format!("{ctx}: missing or non-integer `{key}`"))?;
    i32::try_from(raw).map_err(|_| format!("{ctx}: `{key}` value {raw} does not fit in i32"))
}

/// One `[enumerations.<key>]` name-to-index map, sorted by name.
fn index_map_field(table: &toml::Table, key: &str, ctx: &str) -> Result<Vec<(String, i32)>> {
    let map = table
        .get(key)
        .and_then(toml::Value::as_table)
        .ok_or_else(|| format!("{ctx}: missing `{key}` table"))?;
    let mut out = Vec::new();
    for (name, value) in map {
        let raw = value
            .as_integer()
            .ok_or_else(|| format!("{ctx}.{key}: non-integer index {value:?} for `{name}`"))?;
        let index = i32::try_from(raw)
            .map_err(|_| format!("{ctx}.{key}: index {raw} of `{name}` does not fit in i32"))?;
        out.push((name.clone(), index));
    }
    out.sort_by(|a, b| a.0.cmp(&b.0));
    Ok(out)
}

